      <h2>3. Step-by-Step Insurance Claim Process</h2>
      <p>If any item is damaged or compromised upon arrival at your new residence, follow our transparent 4-step claim protocol:</p>
      <ol>
          <li><strong>Note Damage on the Lorry Receipt (LR Copy):</strong> Before signing the delivery acknowledgement, clearly write the damaged package number and description on the driver's delivery sheet.</li>
          <li><strong>Photograph & Video Record:</strong> Take clear photographs and high-resolution videos of the damaged item before removing the outer packing materials.</li>
          <li><strong>Submit Claim Intimation:</strong> Send photos and your LR receipt copy to apnapackersmovers@gmail.com within 48 hours of delivery.</li>
          <li><strong>Surveyor Assessment & Payout:</strong> An authorized insurance surveyor evaluates the claim and settlement is remitted directly to your bank account.</li>
      </ol>

      
    <h2>4. Declaring Consignment Valuation Accurately</h2>
    <p>Under-declaring or over-declaring your goods value can lead to complications during claim settlements:</p>
    <ul>
        <li><strong>Fair Market Value vs Purchase Value:</strong> Declare the current replacement cost of your appliances and furniture. For an LED TV bought 2 years ago for ₹50,000, current replacement cost of an equivalent model should be declared.</li>
        <li><strong>Itemized High-Value Declarations:</strong> Individual items valued above ₹25,000 (such as double-door refrigerators, luxury sofas, or gaming PCs) must be explicitly listed on the inventory sheet with brand name and serial numbers.</li>
        <li><strong>Keep Purchase Invoices Handy:</strong> Retain digital copies of purchase bills for newly bought appliances to expedite insurance surveyor approvals.</li>
    </ul>

    <h2>5. Common Pitfalls that Void Insurance Claims</h2>
    <ol>
        <li>Signing the Lorry Receipt (LR) as "Received in Good Condition" without inspecting delivered boxes. Always write "Subject to internal unpacking inspection" if boxes cannot be unboxed immediately.</li>
        <li>Failing to report damages within 48 hours of delivery.</li>
        <li>Self-packing fragile items without professional bubble wrapping (insurer may classify as improper packing by consignor).</li>
    </ol>
  

